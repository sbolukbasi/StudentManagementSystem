    private void DeleteStudentButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteStudentButtonActionPerformed
     if (StudentID.getText().trim().isEmpty()) {
       JOptionPane.showMessageDialog(null, "Please enter a Student ID first!");
       return;
     }
     String sql = "delete from Group2_Students where StudentID = ?;";
     try
     {
         conn=OnlineDB.connectOnlineDB();
         pst = conn.prepareStatement(sql);
         pst.setString(1,StudentID.getText());
         
         int result = pst.executeUpdate();

         if (result > 0) {
            JOptionPane.showMessageDialog(null, "Student deleted successfully!");
            StudentID.setText("");
            jTextArea1.setText("");
         } else {
            JOptionPane.showMessageDialog(null, "No student found with this ID!");
         }
     }
     catch(Exception e)
     {
         JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
     }
    }//GEN-LAST:event_DeleteStudentButtonActionPerformed

