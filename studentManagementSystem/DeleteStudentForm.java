    private void SearchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchButtonActionPerformed
                                            
    String sql = "SELECT * FROM Group2_Students WHERE StudentID = ?";
    
    try {
        conn=OnlineDB.connectOnlineDB();
        pst = conn.prepareStatement(sql);
        pst.setString(1, StudentID.getText());
        rs = pst.executeQuery();

        if (rs.next()) {
            String name = rs.getString("Name");
            String surname = rs.getString("Surname");
            String gender = rs.getString("Gender");
            String email = rs.getString("Email");
            String department = rs.getString("Department");
            String year = rs.getString("Year");
            String gpa = rs.getString("Gpa"); 

         
            jTextArea1.setText(
                               "Full Name  : " + name + " " + surname + "\n" +
                               "Gender     : " + gender + "\n" +
                               "E-mail     : " + email + "\n" +
                               "Department : " + department + "\n" +
                               "Year       : " + year + "\n" +
                               "GPA        : " + gpa + "\n" 
                               );
        } else {
            jTextArea1.setText("No student record found for ID: " + StudentID.getText());
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Search Error: " + e.getMessage());
    }

    }//GEN-LAST:event_SearchButtonActionPerformed

